"""Regenerate static re-exports for lazy APIs without importing optional packages."""

from __future__ import annotations

import ast
from pathlib import Path


def export_lines(exports: dict[str, str], module: str) -> list[str]:
    return [
        f"from {origin if origin.startswith('anomx.') else f'{module}.{origin}'} "
        f"import {name} as {name}"
        for name, origin in sorted(exports.items())
    ]


def generate(root: Path) -> dict[Path, str]:
    outputs = {}
    for source in sorted(root.rglob("__init__.py")):
        tree = ast.parse(source.read_text())
        for node in tree.body:
            if not isinstance(node, ast.Assign):
                continue
            if not any(
                isinstance(target, ast.Name) and target.id in {"_EXPORTS", "_LAZY_EXPORTS"}
                for target in node.targets
            ):
                continue
            exports = ast.literal_eval(node.value)
            module = ".".join(source.parent.relative_to(root.parent).parts)
            lines = ['"""Generated by tools/generate_public_stubs.py; do not edit."""', ""]
            lines.extend(export_lines(exports, module))
            if source.parent == root:
                lines.extend(["", "__version__: str"])
            lines.extend(
                ["", "__all__ = [", *[f"    {name!r}," for name in sorted(exports)], "]", ""]
            )
            outputs[source.with_suffix(".pyi")] = "\n".join(lines)
    return outputs


if __name__ == "__main__":
    for path, content in generate(Path(__file__).resolve().parents[1] / "src" / "anomx").items():
        path.write_text(content)
